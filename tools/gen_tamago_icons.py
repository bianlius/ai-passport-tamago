#!/usr/bin/env python3
"""Pack the reviewed 24 px Lucide PNGs into the Tama-Go menu icon header."""
from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/images/tamago_lucide"
OUTPUT = ROOT / "main/tamago_icons.h"
SIZE = 24
ICONS = (
    ("info", "information"),
    ("utensils", "food"),
    ("toilet", "toilet/flush"),
    ("door-open", "doors"),
    ("user-round", "Gotchi figure"),
    ("graduation-cap", "training"),
    ("briefcase-medical", "medicine"),
    ("radio-tower", "IR communication"),
    ("images", "album"),
    ("bell", "attention"),
)


def render() -> str:
    blocks = []
    for name, meaning in ICONS:
        assert (ASSETS / f"{name}.svg").is_file(), f"Missing SVG: {name}"
        with Image.open(ASSETS / f"{name}.png") as image:
            assert image.size == (SIZE, SIZE), f"Wrong size: {name}"
            pixels = list(image.convert("RGBA").getchannel("A").getdata())
        coverage = [(alpha * 15 + 127) // 255 for alpha in pixels]
        assert any(value == 15 for value in coverage), f"Empty icon: {name}"
        packed = [(coverage[i] << 4) | coverage[i + 1]
                  for i in range(0, len(coverage), 2)]
        rows = ["        " + ", ".join(f"0x{value:02x}" for value in packed[i:i + 12]) + ","
                for i in range(0, len(packed), 12)]
        blocks.append(f"    /* {meaning}: {name}.svg */\n    {{\n" + "\n".join(rows) + "\n    },")
    return f'''/* Generated by tools/gen_tamago_icons.py from assets/images/tamago_lucide.
 * Lucide Icons, ISC License; see assets/images/tamago_lucide/LICENSE.
 * 24 x 24, 4-bit alpha, two pixels per byte, high nibble first.
 */
#pragma once
#include <stdint.h>

#define TAMAGO_ICON_SIZE {SIZE}
#define TAMAGO_ICON_BYTES ({SIZE} * {SIZE} / 2)

static const uint8_t tamago_icon_alpha[{len(ICONS)}][TAMAGO_ICON_BYTES] = {{
{chr(10).join(blocks)}
}};
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = render()
    if args.check:
        assert OUTPUT.read_text() == source, "Regenerate Tama-Go icons"
        print("Tama-Go icon bitmap current")
    else:
        OUTPUT.write_text(source)
        print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(source)} bytes)")


if __name__ == "__main__":
    main()
