#!/usr/bin/env python3
"""Generate the small LVGL 9 menu font from LVGL's OFL Noto Sans SC test font."""
from __future__ import annotations

import argparse
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "managed_components/lvgl__lvgl/tests/src/test_files/fonts/noto/NotoSansSC-Regular.ttf"
OUTPUT = ROOT / "assets/fonts/tamago_menu_font_14.c"
INVENTORY = ROOT / "assets/fonts/tamago_menu_chars.txt"
INPUTS = (ROOT / "main/tamago_main.c", ROOT / "main/t7_figures.c")
SIZE = 14


def chars() -> list[str]:
    # ASCII for figure numbers and English original names; all non-ASCII UI literals.
    found = set(chr(cp) for cp in range(32, 127))
    for path in INPUTS:
        for literal in re.findall(r'"(?:\\.|[^"\\])*"', path.read_text()):
            found.update(c for c in literal if ord(c) > 127)
    return sorted(found, key=ord)


def glyph(font: ImageFont.FreeTypeFont, char: str) -> tuple[int, int, int, int, int, bytes]:
    x0, y0, x1, y1 = font.getbbox(char, anchor="ls")
    width, height = x1 - x0, y1 - y0
    advance = round(font.getlength(char) * 16)
    if not width or not height:
        return advance, 0, 0, 0, 0, b""
    bitmap = Image.new("L", (width, height), 0)
    ImageDraw.Draw(bitmap).text((-x0, -y0), char, font=font, anchor="ls", fill=255)
    pixels = [round(pixel * 15 / 255) for pixel in bitmap.getdata()]
    packed = bytes((pixels[i] << 4) | (pixels[i + 1] if i + 1 < len(pixels) else 0)
                   for i in range(0, len(pixels), 2))
    # PLAIN 4-bpp high-nibble-first must round-trip to the rasterized values.
    decoded = [v for byte in packed for v in (byte >> 4, byte & 15)][:len(pixels)]
    assert decoded == pixels
    return advance, width, height, x0, -y1, packed


def render() -> tuple[str, str]:
    if not SOURCE.exists():
        raise SystemExit(f"Missing source font: {SOURCE}")
    font = ImageFont.truetype(str(SOURCE), SIZE)
    inventory = chars()
    ascii_chars = [c for c in inventory if ord(c) < 127]
    others = [c for c in inventory if ord(c) >= 127]
    assert len(ascii_chars) == 95
    chunks: list[str] = []
    descriptors = ["    {0, 0, 0, 0, 0, 0}, /* reserved */"]
    offset = 0
    for char in inventory:
        adv, width, height, ox, oy, bitmap = glyph(font, char)
        chunks.append(f"    /* U+{ord(char):04X} */")
        chunks.extend("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 12]) + ","
                      for i in range(0, len(bitmap), 12))
        descriptors.append(f"    {{{offset}, {adv}, {width}, {height}, {ox}, {oy}}},")
        offset += len(bitmap)
    base = ord(others[0])
    unicode_offsets = [ord(char) - base for char in others]
    assert max(unicode_offsets) <= 0xFFFF
    offsets = ", ".join(str(value) for value in unicode_offsets)
    source = f'''/* Generated by tools/gen_tamago_font.py from NotoSansSC-Regular.ttf.
 * Font derivative licensed under SIL OFL 1.1; see assets/fonts/OFL.txt.
 * Size 14, 4 bpp PLAIN, {len(inventory)} glyphs, {offset} bitmap bytes.
 */
#include "lvgl.h"

static const uint8_t glyph_bitmap[] = {{
{chr(10).join(chunks)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{chr(10).join(descriptors)}
}};

static const uint16_t unicode_list[] = {{ {offsets} }};
const uint32_t tamago_menu_codepoints[] = {{ {', '.join(str(ord(c)) for c in inventory)}, 0 }};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = 32, .range_length = 95, .glyph_id_start = 1,
      .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,
      .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},
    {{.range_start = {base}, .range_length = {max(unicode_offsets) + 1},
      .glyph_id_start = 96, .unicode_list = unicode_list,
      .glyph_id_ofs_list = NULL, .list_length = {len(others)},
      .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 2, .bpp = 4,
    .kern_classes = 0, .bitmap_format = 0, .stride = 0,
}};

const lv_font_t tamago_menu_font_14 = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = 18, .base_line = 4, .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -2, .underline_thickness = 1,
    .dsc = &font_dsc,
}};
'''
    return source, "".join(others) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source, inventory = render()
    if args.check:
        assert OUTPUT.read_text() == source, "Regenerate menu font"
        assert INVENTORY.read_text() == inventory, "Regenerate menu character inventory"
        print("Menu font and character inventory current")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(source)
        INVENTORY.write_text(inventory)
        print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(source)} bytes)")


if __name__ == "__main__":
    main()
